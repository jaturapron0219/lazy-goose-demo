window.QUESTION_POOL = (function () {
    const pool = {};
    window.QUESTION_SETS.forEach((set, si) => {
        set.forEach((q, qi) => {
            const id = `s${si + 1}q${qi + 1}`;
            pool[id] = Object.assign({ id, slot: qi + 1 }, q);
        });
    });
    return pool;
})();

// คืนโจทย์ตามรหัส (ถ้าไม่พบใช้ชุดที่ 1)
window.getQuestion = function (id, fallbackIndex) {
    return window.QUESTION_POOL[id] || window.QUESTION_POOL[`s1q${fallbackIndex}`];
};
